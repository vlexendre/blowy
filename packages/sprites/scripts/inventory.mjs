// Régénère docs/mobile/assets-inventory.md depuis le manifest compilé (pnpm --filter @blowy/sprites build d'abord).
import { writeFileSync } from 'node:fs';
import process from 'node:process';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ACCESSORIES, FRAME_SEQUENCES, EGGS, HYBRID_BABIES, spriteInventory } from '../dist/index.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const rows = spriteInventory();
const count = (s) => rows.filter((r) => r.status === s).length;
const out = [];
out.push('# Inventaire des assets sprites');
out.push('');
out.push('> Généré par `node packages/sprites/scripts/inventory.mjs` (après `pnpm --filter @blowy/sprites build`). Ne pas éditer à la main.');
out.push('> Source : maquette V4 (`design/v4-reference/assets`) copiée dans `packages/sprites/assets` sous des noms parlants.');
out.push('');
out.push(`Matrice 4 espèces × 3 stades × 12 poses = ${rows.length} combinaisons : **${count('PRESENT')} dessinées**, **${count('FALLBACK')} en repli déclaré**, **${count('PLACEHOLDER')} placeholder**.`);
out.push('');
out.push('Règle de repli (packages/sprites/src/resolve.ts) : pose demandée → chaîne `POSE_FALLBACKS` (même stade) → stade jeune mis à l’échelle (bébé ×0,72, adulte ×1,12) → placeholder. Une pose d’état (malade, endormi, affamé, triste) remplacée est toujours accompagnée d’un overlay (icône + libellé vocalisé) pour que l’état ne soit pas perdu.');
out.push('');
out.push('Pour remplacer un repli : déposer le fichier PNG/WebP transparent au chemin `packages/sprites/assets/<espèce>/<stade>/<pose>.webp`, l’ajouter dans `POSE_SPRITES` (`src/catalog.ts`), lancer `pnpm --filter @blowy/sprites scan` puis ce script. Le test `manifest.test.ts` vérifie chemins, transparence, ligne de sol et cet inventaire.');
out.push('');
out.push('## Poses manquantes (repli)');
out.push('');
out.push('| Espèce | Stade | Pose | Rendu actuel |');
out.push('|---|---|---|---|');
for (const r of rows.filter((x) => x.status !== 'PRESENT')) out.push(`| ${r.species} | ${r.stage} | ${r.pose} | ${r.resolvedTo} |`);
out.push('');
out.push('## Poses présentes');
out.push('');
for (const r of rows.filter((x) => x.status === 'PRESENT')) out.push(`- ${r.species} ${r.stage} ${r.pose} → \`${r.resolvedTo.replace(/^.*\((.*)\).*$/, '$1')}\``);
out.push('');
out.push('## Animations (4 frames attendues)');
out.push('');
out.push('| Espèce | Marche | Saut |');
out.push('|---|---|---|');
for (const [s, seq] of Object.entries(FRAME_SEQUENCES)) out.push(`| ${s} | ${seq.walk.source} (${seq.walk.frames.length} frames) | ${seq.jump.source} (${seq.jump.frames.length} frames) |`);
out.push('');
out.push('`dedicated` = frames dessinées ; `composed` = séquence composée de poses existantes (présentation → bond → présentation) ; `procedural` = aucune frame : le PetRenderer déplace la pose de présentation avec un rebond (manque à combler par le pack).');
out.push('');
out.push('## Accessoires (12/12 présents)');
out.push('');
for (const a of Object.values(ACCESSORIES)) out.push(`- ${a.id} (${a.slot}) → \`${a.path}\``);
out.push('');
out.push('Placement : ancrage normalisé dans la boîte opaque par espèce et par slot (`ACCESSORY_PLACEMENTS`), échelle par stade (`STAGE_PLACEMENT_SCALE`). Mesuré à l’œil sur la maquette sur la pose de présentation ; le pack final devra fournir des ancrages par pose (tête qui bouge en saut/danse).');
out.push('');
out.push('## Œufs et bébés');
out.push('');
for (const [k, v] of Object.entries(EGGS)) out.push(`- œuf ${k} → ${v ?? 'manquant (repli : œuf partagé générique)'}`);
for (const [k, v] of Object.entries(HYBRID_BABIES)) out.push(`- bébé hybride ${k} → \`${v}\``);
out.push('- Autres combinaisons de bébés : manquantes → variante explicite du parent « corps » (P-5.17).');
out.push('');
out.push('## Autres manques identifiés');
out.push('');
out.push('- Stades BÉBÉ (sauf Nino) et ADULTE (toutes espèces) : aucun dessin. Le dessin « Adulte » référencé par V4-Fiche (`324d5cda…`) n’est pas présent dans l’export.');
out.push('- Assets référencés par la maquette mais absents de l’export : `6400a21a…` (Nino fâché), `e17f7a5a…` (alerte pet), `ba10d999…` (mission manger), `47cd8823…` (gel de série). Remplacés par des icônes vectorielles / poses existantes.');
out.push('- Les sprites « Claude » (ancienne mascotte V1–V3 : `3d012c30…`, `4f1732e4…`, `5b3fde8a…`, `76e13d29…`, `bc9d8525…`, `c3d2f694…`, `c91c8c3f…`, `46a416be…`, `006eac88…`, `792b978a…`) ne sont pas utilisés : hors casting V4.');
out.push('- Polices Bricolage Grotesque / Inter : instances statiques générées depuis `@fontsource-variable/*` (licence OFL) par `apps/mobile/scripts/fonts/build-fonts.py` → `apps/mobile/assets/fonts/`.');
out.push('');
writeFileSync(join(root, 'docs', 'mobile', 'assets-inventory.md'), out.join('\n'));
process.stderr.write(`ok ${rows.length}\n`);
