const days = (n: number): string => `${n} ${plural(n, { one: 'jour', other: 'jours' })}`;
const daysEn = (n: number): string => `${n} ${plural(n, { one: 'day', other: 'days' })}`;
/** Heure pleine à l'américaine (l'anglais de Minimoa est américain) : « 6 PM ». */
const usHour = (h: number): string => `${h % 12 === 0 ? 12 : h % 12} ${h % 24 < 12 ? 'AM' : 'PM'}`;
const daysEs = (n: number): string => `${n} ${plural(n, { one: 'día', other: 'días' })}`;
const daysPt = (n: number): string => `${n} ${plural(n, { one: 'dia', other: 'dias' })}`;
const daysNl = (n: number): string => `${n} ${plural(n, { one: 'dag', other: 'dagen' })}`;

/** Titre en deux lignes, le dernier mot estompé (« UN MOT À / UN LIEN. ») : même découpe dans les quatre traductions. */
const lastWordDim = (label: string): TitleSegment[] => {
  const words = label.toUpperCase().replace(/\.$/, '').split(' ');
  if (words.length < 2) return [{ text: `${words[0] ?? ''}.` }];
  return [{ text: `${words.slice(0, -1).join(' ')}\n` }, { text: `${words[words.length - 1] ?? ''}.`, dim: true }];
};

